/**
 * Индивидуальные тарифы для машин, которые не укладываются в общую сетку скидок.
 *
 * Ключ — id машины, значение — стоимость аренды за весь срок ДО акции (฿).
 * Между опорными точками суточная ставка интерполируется линейно,
 * за их пределами берётся ближайшая опорная ставка.
 */
export type PriceAnchors = Record<number, number>;

/**
 * Одинаковая цена за срок на каждом дне диапазона [from; to].
 * Нужна там, где итог упирается в потолок (например, в цену месячного пакета):
 * ставка между опорными точками идёт по прямой, а «итог постоянен» — это
 * гипербола, поэтому ставим точку на каждый день, иначе итог уползёт вверх.
 */
const flatTotal = (from: number, to: number, total: number): PriceAnchors =>
  Object.fromEntries(Array.from({ length: to - from + 1 }, (_, i) => [from + i, total]));

/**
 * Бюджетные машины с базой 500 ฿/сут: по общей сетке месяц выходил 6 000 ฿
 * (−67% к суткам) — это ниже рынка. Задаём месяц явно, недельную цену
 * оставляем прежней, чтобы сдвинулся только длинный хвост.
 *
 * Эти машины вне акции (PROMO.excludedCarIds / excludedCategories),
 * поэтому цены здесь финальные — пересчёта на скидку, как у BMW, нет.
 */
const BUDGET_500 = {
  3: 1_200,   // 400 ฿/сут — как было
  7: 2_100,   // 300 ฿/сут — как было
  30: 8_000,  // было 6 000 ฿
};

